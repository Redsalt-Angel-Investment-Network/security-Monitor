"""One-time setup: asks a few questions and writes .env with fresh keys.

    python scripts/setup.py

Then start everything with:
    docker compose up -d --build

Every source gets its OWN random API key, so a key leaked from one machine
can be revoked without touching the others. .env holds secrets: it is in
.gitignore - never commit it.
"""
import os
import secrets
import shutil
import sys
from datetime import datetime
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parent.parent
ENV = ROOT / ".env"


def ask(question: str, default: str = "") -> str:
    suffix = f" [{default}]" if default else ""
    answer = input(f"{question}{suffix}: ").strip()
    return answer or default


def ask_list(question: str) -> list[str]:
    return [v.strip() for v in ask(question).split(",") if v.strip()]


def main() -> None:
    print("security-monitor setup - press Enter to skip optional questions.\n")
    if ENV.exists():
        if ask(".env already exists. Replace it? (old one is backed up) y/N", "n").lower() != "y":
            sys.exit("Keeping the existing .env.")
        backup = ENV.with_name(f".env.backup-{datetime.now():%Y%m%d-%H%M%S}")
        shutil.copy2(ENV, backup)
        print(f"Backed up to {backup.name}\n")

    urls = []
    while not urls:
        urls = ask_list("Website / API URLs to watch, comma-separated (e.g. https://app.example.com)")
        bad = [u for u in urls if urlsplit(u).scheme not in ("http", "https") or not urlsplit(u).hostname]
        if bad:
            print(f"  Not a full URL: {', '.join(bad)} - include https://")
            urls = []
    print("  Only add sites you own or have permission to check.\n")

    domains = ask_list("Domains for email-spoofing and expiry checks (Enter = work them out from the URLs)")
    slack = ask("Slack incoming-webhook URL for alerts (optional)")
    smtp_host = ask("SMTP server for email alerts, e.g. smtp.gmail.com (optional)")
    smtp = {}
    if smtp_host:
        smtp = {
            "SM_SMTP_HOST": smtp_host,
            "SM_SMTP_PORT": ask("SMTP port", "587"),
            "SM_SMTP_USER": ask("SMTP username"),
            "SM_SMTP_PASSWORD": ask("SMTP password (an app password, not your main one)"),
            "SM_EMAIL_TO": ask("Send alerts to (comma-separated emails)"),
        }
    digest_hour = ask("Hour (UTC, 0-23) for the daily digest", "7")

    webcheck_key = secrets.token_urlsafe(32)
    agents_key = secrets.token_urlsafe(32)

    lines = [
        "# Generated by scripts/setup.py - contains SECRETS, never commit this file.",
        "",
        "# Keys the collector accepts, one per source (name=key). Revoke one by deleting it.",
        f"SM_API_KEYS=webcheck={webcheck_key},agents={agents_key}",
        "# The web checker's own key (used by docker-compose.yml).",
        f"SM_WEBCHECK_KEY={webcheck_key}",
        "# Key for endpoint agents (windows_agent.py, simulate.py) run on this machine.",
        f"SM_API_KEY={agents_key}",
        "",
        f"SM_CHECK_URLS={','.join(urls)}",
        f"SM_CHECK_DOMAINS={','.join(domains)}",
        "",
        "SM_INSTANT_MIN_SEVERITY=high",
        f"SM_DIGEST_HOUR_UTC={digest_hour}",
        f"SM_SLACK_WEBHOOK_URL={slack}",
    ]
    lines += [f"{k}={v}" for k, v in smtp.items()]
    lines += ["", "SM_COLLECTOR_URL=http://127.0.0.1:8000", ""]
    ENV.write_text("\n".join(lines), encoding="utf-8")
    if os.name == "posix":
        ENV.chmod(0o600)  # readable by you only

    print(f"\nWrote {ENV}")
    if not (slack or smtp_host):
        print("No Slack or email set: alerts will only appear in the collector's log.")
    print("\nNext:\n  docker compose up -d --build\n  docker compose logs -f collector")


if __name__ == "__main__":
    main()
